import { writeFile } from 'node:fs/promises';
import { argbFromHex, Hct, hexFromArgb, SchemeTonalSpot } from '@material/material-color-utilities';
import { springToLinear } from '@kyralabs/m3e-motion';

// Google's HCT palettes and semantic roles, rather than hand-picked light/dark colors.
// https://github.com/material-foundation/material-color-utilities
const roles = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'surface',
  'onSurface',
  'onSurfaceVariant',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'outline',
  'outlineVariant',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'inverseSurface',
  'inverseOnSurface',
  'inversePrimary',
  'scrim',
] as const;
const source = Hct.fromInt(argbFromHex('#3f5f90'));
const schemes = Object.fromEntries(
  ['light', 'dark'].map((mode) => {
    const scheme = new SchemeTonalSpot(source, mode === 'dark', 0);
    return [mode, Object.fromEntries(roles.map((role) => [role, hexFromArgb(scheme[role])]))];
  }),
);
const kebab = (value: string) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
// MotionSchemeKeyTokens.kt: expressive fast spatial / fast effects.
// https://github.com/androidx/androidx/blob/androidx-main/compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/tokens/MotionSchemeKeyTokens.kt
const spatial = springToLinear({ dampingRatio: 0.6, stiffness: 800 });
const effects = springToLinear({ dampingRatio: 1, stiffness: 3800 });
const header = '/* Generated by npm run theme:generate. Do not edit by hand. */\n';
const css = Object.entries(schemes)
  .map(
    ([mode, colors]) =>
      `${mode === 'light' ? ':root' : ":root[data-theme='dark']"} {\n${Object.entries(colors)
        .map(([role, color]) => `  --md-sys-color-${kebab(role)}: ${color};`)
        .join('\n')}\n}`,
  )
  .join('\n');
await writeFile(
  new URL('../src/material/tokens.css', import.meta.url),
  `${header}${css}\n:root {\n  --md-sys-motion-fast-spatial: ${spatial.easing};\n  --md-sys-motion-fast-spatial-duration: ${spatial.durationMillis}ms;\n  --md-sys-motion-fast-effects: ${effects.easing};\n  --md-sys-motion-fast-effects-duration: ${effects.durationMillis}ms;\n}\n`,
);
await writeFile(
  new URL('../src/material/colors.ts', import.meta.url),
  `// Generated by npm run theme:generate.\nexport const materialColors = ${JSON.stringify(schemes, null, 2)} as const;\n`,
);
console.log('Generated Material HCT color roles and Expressive spring tokens.');
