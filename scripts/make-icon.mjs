// Copy the Shizhi artwork (Pixel 2026 style) unchanged into platform resources.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

const source = new URL('../assets/icons/', import.meta.url);
const root = new URL('../', import.meta.url);
for (const directory of ['build/', 'public/', 'android/app/src/main/res/drawable/'])
  await mkdir(new URL(directory, root), { recursive: true });

for (const [original, target] of [
  ['Shizhi_Windows.ico', 'build/icon.ico'],
  ['Shizhi_macOS.icns', 'build/icon.icns'],
  ['Shizhi_Windows_1024.png', 'build/icon.png'],
  ['Shizhi_Windows.svg', 'public/icon.svg'],
  ['Shizhi_Windows_256.png', 'public/tray.png'],
  ['Shizhi_macOS_256.png', 'public/tray-macos.png'],
])
  await copyFile(new URL(original, source), new URL(target, root));

// The artwork uses gradients, so Android vectors are supplied ready-made instead of
// being converted from the SVGs. Only a provenance comment is added.
for (const [original, target] of [
  ['Shizhi_Android_legacy.xml', 'app_icon.xml'],
  ['Shizhi_Android_foreground.xml', 'app_icon_foreground.xml'],
  ['Shizhi_Android_monochrome.xml', 'app_icon_monochrome.xml'],
]) {
  const xml = await readFile(new URL(original, source), 'utf8');
  const declaration = '<?xml version="1.0" encoding="utf-8"?>\n';
  if (!xml.startsWith(declaration)) throw new Error(`Unexpected vector header: ${original}`);
  await writeFile(
    new URL(`android/app/src/main/res/drawable/${target}`, root),
    `${declaration}<!-- Generated by npm run icons from assets/icons/${original}. -->\n${xml.slice(declaration.length)}`,
  );
}
console.log('Updated desktop, web and Android Shizhi icons from assets/icons/.');
