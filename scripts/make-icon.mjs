// Copy the supplied Shizhi artwork unchanged; Android only adapts its vector viewport.
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';

const source = new URL('../assets/icons/', import.meta.url);
const root = new URL('../', import.meta.url);
for (const directory of ['build/', 'public/', 'android/app/src/main/res/drawable/'])
  await mkdir(new URL(directory, root), { recursive: true });

for (const [original, target] of [
  ['Shizhi_Windows.ico', 'build/icon.ico'],
  ['Shizhi_macOS.icns', 'build/icon.icns'],
  ['Shizhi_Windows_1024.png', 'build/icon.png'],
  ['Shizhi_Windows.svg', 'public/icon.svg'],
  ['Shizhi_Windows_256.png', 'public/tray.png'],
  ['Shizhi_macOS_256.png', 'public/tray-macos.png'],
])
  await copyFile(new URL(original, source), new URL(target, root));

// Both supplied SVGs have one centred scale group and solid filled paths.
// Keep every path and colour, including the macOS tile, without raster tracing.
for (const [original, target, inset] of [
  ['Shizhi_macOS.svg', 'app_icon.xml', 1],
  ['Shizhi_Windows.svg', 'app_icon_foreground.xml', 0.72],
]) {
  const svg = await readFile(new URL(original, source), 'utf8');
  const groupAt = svg.indexOf('<g transform=');
  const scale = Number(svg.match(/scale\(([\d.]+)\)/)?.[1]);
  if (groupAt < 0 || !Number.isFinite(scale)) throw new Error(`Unsupported SVG: ${original}`);
  const paths = [...svg.matchAll(/<path\b[^>]*\/>/g)].map((match) => {
    const data = match[0].match(/\bd="([^"]+)"/)?.[1];
    const fill = match[0].match(/\bfill="(#[\da-f]{6})"/i)?.[1];
    if (!data || !fill) throw new Error(`Unsupported path in ${original}`);
    return {
      grouped: match.index > groupAt,
      xml: `    <path android:fillColor="${fill}" android:pathData="${data}" />`,
    };
  });
  const content = [
    ...paths.filter((item) => !item.grouped).map((item) => item.xml),
    `    <group android:pivotX="512" android:pivotY="512" android:scaleX="${scale * inset}" android:scaleY="${scale * inset}">`,
    ...paths.filter((item) => item.grouped).map((item) => `    ${item.xml}`),
    '    </group>',
  ].join('\n');
  await writeFile(
    new URL(`android/app/src/main/res/drawable/${target}`, root),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by npm run icons from assets/icons/${original}. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="1024" android:viewportHeight="1024">\n${content}\n</vector>\n`,
  );
}
console.log('Updated desktop, web and Android Shizhi icons from assets/icons/.');
